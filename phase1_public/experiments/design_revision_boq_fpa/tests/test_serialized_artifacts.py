from __future__ import annotations

import csv
import hashlib
import json
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


class SerializedArtifactOracleTests(unittest.TestCase):
    """Independent checks for canonical input and post-run serialised artifacts.

    These assertions intentionally do not import production metric functions.
    Expected values are fixed for the 24-case oracle and are checked from the
    JSONL/JSON/CSV files written by the entry point.
    """

    def test_canonical_input_fixture(self) -> None:
        path = ROOT / "inputs" / "cases.jsonl"
        if not path.is_file():
            self.skipTest("canonical input is generated before the experiment run")
        cases = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
        self.assertEqual(len(cases), 24)
        counts: dict[str, int] = {}
        for case in cases:
            counts[case["case_type"]] = counts.get(case["case_type"], 0) + 1
            self.assertTrue(case["design_revision"]["marked_locator"])
            self.assertTrue(case["candidates"])
            for candidate in case["candidates"]:
                self.assertTrue(candidate["source_version"])
                self.assertTrue(candidate["locator"])
            self.assertIn("gold", case)
            self.assertIn("support_evidence", case)
            self.assertIn("conflict_evidence", case)
        self.assertEqual(counts, {
            "explicit_mapping": 6,
            "ambiguous_alternatives": 6,
            "cross_document_version_conflict": 6,
            "insufficient_evidence": 6,
        })

    def test_serialized_outputs_and_manifest_against_independent_oracle(self) -> None:
        metrics_path = ROOT / "outputs" / "metrics.json"
        traces_path = ROOT / "outputs" / "traces.jsonl"
        manifest_path = ROOT / "manifest.json"
        if not (metrics_path.is_file() and traces_path.is_file() and manifest_path.is_file()):
            self.skipTest("serialized outputs are generated by the experiment entry point")
        metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
        if "decision_accuracy" not in metrics["overall"]["M1"]:
            self.skipTest("serialized outputs use the pre-correction metric schema")
        traces = [json.loads(line) for line in traces_path.read_text(encoding="utf-8").splitlines() if line.strip()]
        self.assertEqual(len(traces), 24)
        self.assertNotIn("mapping_accuracy", json.dumps(metrics, ensure_ascii=False))
        expected = {
            "M1": {
                "decision_accuracy": 0.25,
                "gold_accept_recall": 1.0,
                "accepted_accuracy": 0.25,
                "coverage": 1.0,
                "unsupported_attribution": 0.75,
                "high_confidence_error": 0.5,
                "provenance_resolvability": 0.75,
                "appropriate_abstention": 0.0,
            },
            "M2": {
                "decision_accuracy": 1.0,
                "gold_accept_recall": 1.0,
                "accepted_accuracy": 1.0,
                "coverage": 0.25,
                "unsupported_attribution": 0.0,
                "high_confidence_error": 0.0,
                "provenance_resolvability": 1.0,
                "appropriate_abstention": 1.0,
            },
        }
        for method, expected_metrics in expected.items():
            for name, value in expected_metrics.items():
                self.assertEqual(metrics["overall"][method][name], value, f"{method}.{name}")
        for trace in traces:
            for field in ("design_revision", "candidate_boq", "gold", "support_evidence", "conflict_evidence"):
                self.assertIn(field, trace)
            self.assertEqual(set(trace["methods"]), {"M1", "M2"})

        csv_path = ROOT / "outputs" / "metrics.csv"
        with csv_path.open(encoding="utf-8", newline="") as handle:
            rows = list(csv.DictReader(handle))
        self.assertEqual(len(rows), 10)
        self.assertIn("decision_accuracy", rows[0])
        self.assertIn("gold_accept_recall", rows[0])
        self.assertNotIn("mapping_accuracy", rows[0])

        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        paths = [item["path"] for item in manifest["files"]]
        self.assertNotIn("manifest.json", paths)
        self.assertFalse(any("__pycache__" in path or path.endswith(".pyc") or path.startswith("tmp/") for path in paths))
        required = {"inputs/cases.jsonl", "outputs/traces.jsonl", "outputs/metrics.json", "outputs/metrics.csv", "reports/experiment_result.md"}
        self.assertTrue(required.issubset(paths))
        for item in manifest["files"]:
            path = ROOT / item["path"]
            self.assertTrue(path.is_file(), item["path"])
            actual = hashlib.sha256(path.read_bytes()).hexdigest()
            self.assertEqual(actual, item["sha256"], item["path"])


if __name__ == "__main__":
    unittest.main(verbosity=2)
