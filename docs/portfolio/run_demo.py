"""Render existing public retrieval and gate fixtures as inspectable examples.

This is an offline presentation wrapper, not a new model or evaluation.
It uses the public sample corpus and existing synthetic test-fixture factories.
No LLM response is generated and no external service is called.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
from datetime import datetime
import hashlib
from importlib.metadata import version
import json
from pathlib import Path
import platform
import subprocess
import sys
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[2]
PHASE = ROOT / "phase2_public"
sys.path[:0] = [str(PHASE / "src"), str(PHASE / "tests")]

from run_retrieval_test import bm25_rank, build_index  # noqa: E402
from llm_abstention_gate import apply_gate  # noqa: E402
from test_post_llm_gate_v2 import _finding, _runtime  # noqa: E402
from test_task_subconclusion_v1 import fixture  # noqa: E402
from task_subconclusion_v1 import apply_task_gate  # noqa: E402


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).parent / "sample-results")
    args = parser.parse_args()
    out = args.output_dir
    out.mkdir(parents=True, exist_ok=True)

    corpus_file = PHASE / "data/rag/corpus_chunks_public_sample.jsonl"
    labels_file = PHASE / "data/gold/contract_review_final_synthetic_gold_v1.jsonl"
    chunks = read_jsonl(corpus_file)
    label = next(row for row in read_jsonl(labels_file) if row["issue_id"] == "SYN-P1-001-I01")
    counts, idf, _, average = build_index(chunks)
    ranked = bm25_rank(label["document_excerpt"], chunks, counts, idf, average)
    candidates = []
    for rank, (score, index) in enumerate(ranked[:3], 1):
        chunk = chunks[index]
        candidates.append({
            "rank": rank, "bm25_score": round(score, 6),
            **{key: chunk.get(key) for key in ["chunk_id", "title", "article", "source_locator", "normative_level", "text"]},
        })
    retrieval = {
        "example_kind": "public_sample_bm25_retrieval",
        "issue_id": label["issue_id"], "synthetic_input": label["document_excerpt"],
        "corpus_chunk_count": len(chunks),
        "query_policy": "document_excerpt only; gold evidence IDs are not used in retrieval",
        "candidates": candidates,
        "scope": "BM25 on 20 public sample chunks; not the full strict-hierarchy hybrid retriever or a benchmark rerun.",
    }

    gate_inputs = []
    gate_results = []
    for demo_id, unknown in [("DEMO-REVIEW", False), ("DEMO-UNKNOWN-SOURCE", True)]:
        runtime = _runtime(issue_id=demo_id)
        raw = {"findings": [_finding(
            issue_id=demo_id,
            conclusion="requires_human_legal_confirm",
            evidence_ids=["unregistered-source"] if unknown else ["law-1"],
        )]}
        gate_inputs.append({"example_id": demo_id, "runtime": runtime, "preset_response": deepcopy(raw)})
        result = apply_gate(raw, runtime)
        gate_results.append({"issue_id": demo_id, "stage3_gate_result": result})

    contract, raw_task = fixture()
    task_input = {"contract": contract, "preset_response": deepcopy(raw_task)}
    task_result = apply_task_gate(raw_task, contract)

    payloads = {
        "retrieval.json": retrieval,
        "gate-inputs.json": {
            "scope": "Independent existing synthetic fixtures, not downstream outputs of retrieval.json. Responses are preset, not generated by an LLM.",
            "cases": gate_inputs,
        },
        "review.json": gate_results,
        "task-input.json": task_input,
        "task-result.json": task_result,
    }
    for name, value in payloads.items():
        (out / name).write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    summary = [
        "# Generated offline example results", "",
        "Generated by `docs/portfolio/run_demo.py` from public sample data and existing synthetic fixtures. No LLM or external-service call.", "",
        "## Sample retrieval", "",
        f"Synthetic query: {label['document_excerpt']}", "",
        f"Corpus: **{len(chunks)} public sample chunks**; lexical BM25 only.", "",
        "| Rank | Chunk ID | Source locator | BM25 score |", "| --- | --- | --- | ---: |",
    ]
    for item in candidates:
        summary.append(f"| {item['rank']} | `{item['chunk_id']}` | {item['source_locator']} | {item['bm25_score']} |")
    summary += ["", "## Independent gate fixtures", "",
        "The preset responses below are separate synthetic fixtures. They were not generated from the retrieval result above.", "",
        "| Example | Gate status | Result |", "| --- | --- | --- |"]
    for record in gate_results:
        gate = record["stage3_gate_result"]
        findings = gate.get("response", {}).get("findings", [])
        conclusions = ", ".join(f["conclusion_type"] for f in findings) if findings else "No deliverable finding"
        summary.append(f"| `{record['issue_id']}` | `{gate['status']}` | `{conclusions}` |")
    response = task_result["response"]
    summary += ["", "## Incomplete document visibility", "",
        f"Task completion: `{response['task_completion']}`.", "",
        "Pending claims: " + ", ".join(f"`{item}`" for item in response["pending_claim_ids"]) + ".", "",
        "The visible narrative and the unread chart remain separate. Human review is still required; no human decision has been supplied in this demonstration.", ""]
    (out / "RESULTS.md").write_text("\n".join(summary), encoding="utf-8")

    sources = [corpus_file, labels_file, PHASE / "src/run_retrieval_test.py",
        PHASE / "src/llm_abstention_gate.py", PHASE / "src/task_subconclusion_v1.py",
        PHASE / "tests/test_post_llm_gate_v2.py", PHASE / "tests/test_task_subconclusion_v1.py",
        Path(__file__).resolve()]
    manifest = {
        "run_date": datetime.now(ZoneInfo("Asia/Hong_Kong")).isoformat(timespec="seconds"),
        "source_commit_at_execution": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
        "command": "python docs/portfolio/run_demo.py",
        "python": platform.python_version(), "platform": platform.system() + " " + platform.machine(),
        "packages": {name: version(name) for name in ["numpy", "openpyxl", "requests", "sentence-transformers", "torch"]},
        "api_calls": 0, "model_weights_loaded": False, "private_inputs_used": False,
        "source_sha256": {str(p.relative_to(ROOT)): digest(p) for p in sources},
        "artifact_sha256": {name: digest(out / name) for name in [*payloads, "RESULTS.md"]},
    }
    (out / "run-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print((out / "RESULTS.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
